export type SchoolPhysicsTestDef = {
  id: string;
  teacherId: string;
  sectionSlug: string;
  topicSlug: string;
  title: string;
  description: string;
  questions: TestQuestion[];
};

function opt(id: string, text: string) {
  return { id, text };
}

function sc(
  id: string,
  prompt: string,
  options: { id: string; text: string }[],
  correct: string,
  explanation: string,
  maxScore = 1
): TestQuestion {
  return {
    id,
    type: "single_choice",
    prompt,
    maxScore,
    options,
    correctOptionIds: [correct],
    explanation,
  };
}

function mc(
  id: string,
  prompt: string,
  options: { id: string; text: string }[],
  correct: string[],
  explanation: string,
  maxScore = 2
): TestQuestion {
  return {
    id,
    type: "multiple_choice",
    prompt,
    maxScore,
    options,
    correctOptionIds: correct,
    explanation,
  };
}

function shortQ(
  id: string,
  prompt: string,
  answers: string[],
  explanation: string,
  maxScore = 1
): TestQuestion {
  return {
    id,
    type: "short_answer",
    prompt,
    maxScore,
    answerKind: "text",
    correctAnswers: answers,
    explanation,
  };
}

function numQ(
  id: string,
  prompt: string,
  value: string,
  explanation: string,
  tolerance = 0.05,
  maxScore = 2
): TestQuestion {
  return {
    id,
    type: "numeric",
    prompt,
    maxScore,
    answerKind: "number",
    correctAnswers: [value],
    numericTolerance: tolerance,
    explanation,
  };
}

function essayQ(id: string, prompt: string, maxScore = 3): TestQuestion {
  return {
    id,
    type: "essay",
    prompt,
    maxScore,
  };
}

